const assert = require('node:assert/strict');
const {stationCatalog, defaultStationConfig, validateStationConfig, stationAccess} = require('../dist-ts/modules/workstations-model');
assert.equal(new Set(stationCatalog.map(e => e.id)).size, stationCatalog.length);
const config = defaultStationConfig(), rules = config.profiles[0].rules;
for (const entry of stationCatalog) assert.equal(stationAccess(config, entry.id), 'accessible');
rules['section:analisi'] = 'hidden';
assert.equal(stationAccess(config, 'article-orders'), 'accessible', 'Unassigned PCs have all modules ON regardless of stored profiles');
config.activeId = 'default';
rules['section:analisi'] = 'blocked';
assert.equal(stationAccess(config, 'article-orders'), 'blocked');
rules['commercial-analysis-open'] = 'hidden';
assert.equal(stationAccess(config, 'article-orders'), 'hidden');
rules['section:analisi'] = 'accessible';
assert.equal(stationAccess(config, 'article-orders'), 'hidden');
rules['commercial-analysis-open'] = 'accessible';
rules['article-orders'] = 'blocked';
assert.equal(stationAccess(config, 'article-orders'), 'blocked');
assert.equal(stationAccess(config, 'article-offers'), 'accessible');
assert.deepEqual(validateStationConfig(config), config);
assert.equal(validateStationConfig({...config,activeId:''}).activeId,'');
assert.throws(() => validateStationConfig({...config, activeId:'absent'}));
assert.throws(() => validateStationConfig({...config, profiles:[]}));
assert.throws(() => validateStationConfig({...config, profiles:[...config.profiles, {...config.profiles[0], id:'second'}]}));
assert.throws(() => validateStationConfig({...config, profiles:[{...config.profiles[0], rules:{'article-orders':'wrong'}}]}));
assert.throws(() => validateStationConfig({...config, profiles:[{...config.profiles[0], rules:{unknown:'hidden'}}]}));
console.log(`Postazioni: ${stationCatalog.length} sezioni e moduli, ereditarietà e validazione OK.`);
